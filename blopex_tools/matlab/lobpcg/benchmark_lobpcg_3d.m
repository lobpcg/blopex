function benchmark = benchmark_lobpcg_3d(gridShape, blockSize, tolerance, ...
    maxIterations, unpreconditionedMaxIterations, referenceJsonPath, diffJsonPath)
%BENCHMARK_LOBPCG_3D Compare LOBPCG accuracy and runtime on 3-D Laplacians.
%
%   B = BENCHMARK_LOBPCG_3D() runs two grids, [49 50 51] and [50 50 50],
%   with block sizes 4 and 19. Each grid/block-size case runs both the
%   unpreconditioned solver and the modified incomplete-Cholesky
%   preconditioned solver on the same initial vectors. Defaults are
%   tolerance 1e-8, 400 preconditioned iterations, and 2000
%   unpreconditioned iterations. The matrices use 3-D Dirichlet boundaries
%   and are generated by LAPLACIAN_ND.
%
%   B = BENCHMARK_LOBPCG_3D(GRIDSHAPE, BLOCKSIZE, TOLERANCE, MAXITERATIONS,
%   UNPRECONDITIONEDMAXITERATIONS, REFERENCEJSONPATH, DIFFJSONPATH) runs a
%   single grid. GRIDSHAPE must be a row vector with three positive sizes.
%   Empty optional arguments select their defaults. REFERENCEJSONPATH and
%   DIFFJSONPATH accept character vectors or scalar strings.
%
%   Default runs return a compact struct array with one entry per
%   grid/block-size pair. Each entry contains setup, exact eigenvalues,
%   timing, convergence, and accuracy metrics for both solver modes. Large
%   matrices, eigenvectors, and histories are omitted to bound memory use.
%   A custom single-grid call returns full computed/reference eigenvectors,
%   the sparse operator, eigenvalues, and LOBPCG histories.
%
%   ACCURACY METRICS
%   maxEigenvalueError is the maximum absolute error versus exact values
%   from LAPLACIAN_ND. eigenvectorSubspaceError measures computed-subspace
%   leakage outside the exact eigenspace, including repeated eigenvalues at
%   the block cutoff. relativeResidual is norm(A*X-X*diag(lambda),'fro')
%   divided by norm(A*X,'fro'). orthogonalityError is norm(X'*X-I,'fro').
%   failureFlag is zero when all requested eigenpairs converged. Reported
%   times cover matrix generation, exact reference-vector generation,
%   preconditioner setup, and each LOBPCG solve.
%
%   REFERENCE AND DIFF FILES
%   A default run uses benchmark_lobpcg_3d_reference.json beside this file.
%   It creates that baseline only if missing and never overwrites an
%   existing baseline automatically. Every comparison writes or replaces
%   benchmark_lobpcg_3d_reference_diff.json. Cases are matched by grid and
%   block size; new or unmatched configurations are identified in the diff.
%   Use a custom REFERENCEJSONPATH to select another baseline and an
%   optional DIFFJSONPATH to select the diff destination.
%
%   REQUIREMENTS AND REPRODUCIBILITY
%   Requires LOBPCG, LAPLACIAN_ND, ICHOL, and sparse matrix support. The
%   benchmark seeds the random initial vectors and restores the caller's
%   RNG state and any path entries it adds. Block-size-19 unpreconditioned
%   cases can take several minutes. A repeated-eigenvalue warning from
%   LAPLACIAN_ND is expected when the block cutoff crosses a cluster.
%
%   MATLAB:
%       benchmark = benchmark_lobpcg_3d();
%
%   Windows PowerShell with MATLAB:
%       & 'C:\Program Files\MATLAB\R2026b\bin\matlab.exe' `
%         -sd 'C:\Users\uurun\Documents\GitHub\blopex\blopex_tools\matlab\lobpcg' `
%         -batch 'benchmark_lobpcg_3d'
%
%   Windows PowerShell with Octave:
%       & 'C:\Program Files\GNU Octave\Octave-10.2.0\mingw64\bin\octave-cli.exe' `
%         --quiet `
%         --path 'C:/Users/uurun/Documents/GitHub/blopex/blopex_tools/matlab/lobpcg' `
%         --eval 'benchmark_lobpcg_3d'

if nargin < 2 || isempty(blockSize)
    blockSize = 4;
end
if nargin < 3 || isempty(tolerance)
    tolerance = 1e-8;
end
if nargin < 4 || isempty(maxIterations)
    maxIterations = 400;
end
if nargin < 5 || isempty(unpreconditionedMaxIterations)
    unpreconditionedMaxIterations = 2000;
end
if nargin < 6
    referenceJsonPath = '';
end
if nargin < 7
    diffJsonPath = '';
end
referenceJsonPath = normalize_json_path(referenceJsonPath);
diffJsonPath = normalize_json_path(diffJsonPath);
runDefaultGridSet = nargin < 1 || isempty(gridShape);
if runDefaultGridSet
    defaultGridShapes = [49, 50, 51; 50, 50, 50];
    defaultBlockSizes = unique([blockSize, 19], 'stable');
    % Store summaries between cases so large matrices and vectors can be released.
    benchmarkCases = cell(1, ...
        size(defaultGridShapes, 1) * numel(defaultBlockSizes));
    caseIndex = 0;
    for gridIndex = 1:size(defaultGridShapes, 1)
        for blockIndex = 1:numel(defaultBlockSizes)
            caseIndex = caseIndex + 1;
            fullCase = benchmark_lobpcg_3d( ...
                defaultGridShapes(gridIndex, :), defaultBlockSizes(blockIndex), ...
                tolerance, maxIterations, unpreconditionedMaxIterations);
            benchmarkCases{caseIndex} = summarize_benchmark_case(fullCase);
            clear fullCase
        end
    end
    benchmark = [benchmarkCases{:}];
    if isempty(referenceJsonPath)
        scriptFolder = fileparts(mfilename('fullpath'));
        referenceJsonPath = fullfile(scriptFolder, ...
            'benchmark_lobpcg_3d_reference.json');
    end
    update_reference_and_diff(benchmark, referenceJsonPath, diffJsonPath);
    return
end
if numel(gridShape) ~= 3
    error('BLOPEX:benchmark_lobpcg_3d:InvalidGridShape', ...
        'GRIDSHAPE must specify exactly three dimensions.');
end
scriptFolder = fileparts(mfilename('fullpath'));
matlabFolder = fileparts(scriptFolder);
laplacianFolder = fullfile(matlabFolder, 'laplacian');
foldersToCheck = {scriptFolder, laplacianFolder};
currentPathEntries = strsplit(path, pathsep);
addedFolders = {};
% Track only folders added here so caller path entries remain untouched.
for folderIndex = 1:numel(foldersToCheck)
    folder = foldersToCheck{folderIndex};
    if ~any(strcmp(currentPathEntries, folder))
        addpath(folder, '-begin');
        addedFolders{end + 1} = folder; %#ok<AGROW>
    end
end
pathCleanup = onCleanup(@() remove_added_paths(addedFolders));
rehash;
resolvedLobpcgPath = which('lobpcg');
expectedLobpcgPath = fullfile(scriptFolder, 'lobpcg.m');
assert(strcmpi(resolvedLobpcgPath, expectedLobpcgPath), ...
    'Expected LOBPCG at %s but MATLAB resolved it to %s.', ...
    expectedLobpcgPath, resolvedLobpcgPath);

rngState = rng;
rngCleanup = onCleanup(@() rng(rngState));
% Use the same initial block for each mode and restore the caller's RNG state.
rng(0);

boundaries = repmat({'DD'}, 1, 3);
% Request extra exact modes so a repeated eigenvalue crossing the block
% cutoff is compared as a complete eigenspace.
referenceClusterMargin = 16;
buildTimer = tic;
[operatorA, exactEigenvalues] = laplacian_nd(gridShape, boundaries, blockSize);
matrixBuildSeconds = toc(buildTimer);
exactEigenvalues = exactEigenvalues(:);
initialVectors = randn(prod(gridShape), blockSize);
unpreconditioned = run_lobpcg_case(operatorA, initialVectors, ...
    exactEigenvalues, tolerance, unpreconditionedMaxIterations, []);

preconditionerTimer = tic;
preconditionerL = ichol(operatorA, struct('michol', 'on'));
preconditionerFunction = @(vectors) ...
    preconditionerL' \ (preconditionerL \ vectors);
preconditionerSeconds = toc(preconditionerTimer);
preconditioned = run_lobpcg_case(operatorA, initialVectors, ...
    exactEigenvalues, tolerance, maxIterations, preconditionerFunction);

referenceTimer = tic;
[~, expandedEigenvalues, expandedEigenvectors] = laplacian_nd(...
    gridShape, boundaries, min(prod(gridShape), blockSize + referenceClusterMargin));
referenceSeconds = toc(referenceTimer);
cutoffTolerance = 100 * eps('double') * max(1, abs(exactEigenvalues(end)));
referenceSubspaceCount = find(...
    expandedEigenvalues <= exactEigenvalues(end) + cutoffTolerance, 1, 'last');
if isempty(referenceSubspaceCount)
    error('BLOPEX:benchmark_lobpcg_3d:ReferenceSubspaceNotFound', ...
        'Could not find exact eigenvectors spanning the requested cutoff eigenspace.');
end
exactEigenvectors = expandedEigenvectors(:, 1:referenceSubspaceCount);
[exactEigenvectors, ~] = qr(exactEigenvectors, 0);
unpreconditioned.eigenvectorSubspaceError = ...
    eigenvector_subspace_error(exactEigenvectors, unpreconditioned.eigenvectors);
preconditioned.eigenvectorSubspaceError = ...
    eigenvector_subspace_error(exactEigenvectors, preconditioned.eigenvectors);

% Keep the preconditioned solve at top level; retain both modes as named fields.
benchmark = preconditioned;
benchmark.gridShape = gridShape;
benchmark.boundaryConditions = boundaries;
benchmark.blockSize = blockSize;
benchmark.tolerance = tolerance;
benchmark.maxIterations = maxIterations;
benchmark.unpreconditionedMaxIterations = unpreconditionedMaxIterations;
benchmark.referenceSubspaceCount = referenceSubspaceCount;
benchmark.matrixOrder = size(operatorA, 1);
benchmark.operatorA = operatorA;
benchmark.exactEigenvalues = exactEigenvalues;
benchmark.exactEigenvectors = exactEigenvectors;
benchmark.matrixBuildSeconds = matrixBuildSeconds;
benchmark.referenceEigenvectorSeconds = referenceSeconds;
benchmark.preconditionerSeconds = preconditionerSeconds;
benchmark.unpreconditioned = unpreconditioned;
benchmark.preconditioned = preconditioned;

fprintf('\n3-D LOBPCG benchmark\n');
fprintf(['Grid: %s, boundaries: {%s}, matrix order: %d, nonzeros: %d, ', ...
    'block size: %d, tolerance: %.1e\n'], ...
    mat2str(gridShape), strjoin(boundaries, ', '), ...
    size(operatorA, 1), nnz(operatorA), ...
    blockSize, tolerance);
fprintf('Matrix construction: %.3f s\n', matrixBuildSeconds);
fprintf('Exact reference-vector generation: %.3f s\n', referenceSeconds);
print_benchmark_case('Unpreconditioned', unpreconditioned);
fprintf('Modified incomplete-Cholesky setup: %.3f s\n', preconditionerSeconds);
print_benchmark_case('Modified incomplete-Cholesky', preconditioned);

if ~isempty(referenceJsonPath)
    update_reference_and_diff(summarize_benchmark_case(benchmark), ...
        referenceJsonPath, diffJsonPath);
end
end

function result = run_lobpcg_case(operatorA, initialVectors, exactEigenvalues, ...
    tolerance, maxIterations, preconditioner)
solveTimer = tic;
if isempty(preconditioner)
    [eigenvectors, eigenvalues, failureFlag, lambdaHistory, residualNormsHistory] = ...
        lobpcg(initialVectors, operatorA, tolerance, maxIterations, 0);
else
    [eigenvectors, eigenvalues, failureFlag, lambdaHistory, residualNormsHistory] = ...
        lobpcg(initialVectors, operatorA, [], preconditioner, ...
        tolerance, maxIterations, 0);
end
solverSeconds = toc(solveTimer);

imaginaryTolerance = 100 * eps(class(eigenvalues)) * max(1, norm(eigenvalues, 'fro'));
assert(max(abs(imag(eigenvalues))) <= imaginaryTolerance, ...
    'LOBPCG returned eigenvalues with significant imaginary parts.');
eigenvalues = real(eigenvalues(:));
[eigenvalues, order] = sort(eigenvalues);
eigenvectors = eigenvectors(:, order);

operatorAEigenvectors = operatorA * eigenvectors;
residuals = operatorAEigenvectors - bsxfun(@times, eigenvectors, eigenvalues');
residualScale = max(norm(operatorAEigenvectors, 'fro'), eps(class(eigenvectors)));
relativeResidual = norm(residuals, 'fro') / residualScale;
maxEigenvalueError = max(abs(eigenvalues - exactEigenvalues));
orthogonalityError = norm(eigenvectors' * eigenvectors - ...
    eye(size(eigenvectors, 2)), 'fro');
% LOBPCG omits the final residual column from its optional history output.
iterationCount = size(residualNormsHistory, 2) + 1;

result = struct(...
    'eigenvectors', eigenvectors, ...
    'eigenvalues', eigenvalues, ...
    'maxEigenvalueError', maxEigenvalueError, ...
    'relativeResidual', relativeResidual, ...
    'orthogonalityError', orthogonalityError, ...
    'failureFlag', failureFlag, ...
    'iterationCount', iterationCount, ...
    'lambdaHistory', lambdaHistory, ...
    'residualNormsHistory', residualNormsHistory, ...
    'solverSeconds', solverSeconds);
end

function errorValue = eigenvector_subspace_error(referenceVectors, computedVectors)
% Measure computed-vector leakage outside the orthonormal reference subspace.
projectionCoefficients = referenceVectors' * computedVectors;
unrepresentedVectors = computedVectors - referenceVectors * projectionCoefficients;
errorValue = norm(unrepresentedVectors, 'fro') / sqrt(size(computedVectors, 2));
end

function print_benchmark_case(label, result)
fprintf('%s: %.3f s, iterations: %d, convergence flag: %d\n', ...
    label, result.solverSeconds, result.iterationCount, result.failureFlag);
fprintf('  Maximum eigenvalue error: %.3e\n', result.maxEigenvalueError);
fprintf('  Eigenvector subspace error: %.3e\n', result.eigenvectorSubspaceError);
fprintf('  Relative residual: %.3e\n', result.relativeResidual);
fprintf('  Orthonormality error: %.3e\n', result.orthogonalityError);
end

function summary = summarize_benchmark_case(benchmark)
if isfield(benchmark, 'modifiedIncompleteCholesky')
    summary = benchmark;
    return
end

summary = struct(...
    'gridShape', benchmark.gridShape, ...
    'blockSize', benchmark.blockSize, ...
    'tolerance', benchmark.tolerance, ...
    'maxIterations', benchmark.maxIterations, ...
    'unpreconditionedMaxIterations', benchmark.unpreconditionedMaxIterations, ...
    'matrixOrder', benchmark.matrixOrder, ...
    'nonzeroCount', nnz(benchmark.operatorA), ...
    'boundaryConditions', {benchmark.boundaryConditions}, ...
    'referenceSubspaceCount', benchmark.referenceSubspaceCount, ...
    'exactEigenvalues', benchmark.exactEigenvalues, ...
    'matrixBuildSeconds', benchmark.matrixBuildSeconds, ...
    'referenceEigenvectorSeconds', benchmark.referenceEigenvectorSeconds, ...
    'preconditionerSeconds', benchmark.preconditionerSeconds, ...
    'unpreconditioned', summarize_solver_result( ...
        benchmark.unpreconditioned, benchmark.unpreconditionedMaxIterations), ...
    'modifiedIncompleteCholesky', summarize_solver_result( ...
        benchmark.preconditioned, benchmark.maxIterations));
end

function write_benchmark_reference(benchmark, filePath)
filePath = normalize_json_path(filePath);
if isempty(filePath)
    error('BLOPEX:benchmark_lobpcg_3d:InvalidJsonPath', ...
        'A JSON reference path is required to write a baseline.');
end
benchmark = arrayfun(@summarize_benchmark_case, benchmark);
runs = cell(1, numel(benchmark));
for runIndex = 1:numel(benchmark)
    current = benchmark(runIndex);
    runs{runIndex} = struct(...
        'gridShape', current.gridShape, ...
        'boundaryConditions', {current.boundaryConditions}, ...
        'matrixOrder', current.matrixOrder, ...
        'nonzeroCount', current.nonzeroCount, ...
        'referenceSubspaceCount', current.referenceSubspaceCount, ...
        'blockSize', current.blockSize, ...
        'tolerance', current.tolerance, ...
        'exactEigenvalues', current.exactEigenvalues(:).', ...
        'matrixBuildSeconds', current.matrixBuildSeconds, ...
        'referenceEigenvectorSeconds', current.referenceEigenvectorSeconds, ...
        'preconditionerSetupSeconds', current.preconditionerSeconds, ...
        'unpreconditioned', current.unpreconditioned, ...
        'modifiedIncompleteCholesky', current.modifiedIncompleteCholesky);
end

reference = struct(...
    'schemaVersion', 1, ...
    'benchmarkName', '3-D Dirichlet Laplacian LOBPCG comparison', ...
    'generatedAt', benchmark_timestamp(), ...
    'matlabVersion', version, ...
    'runs', {runs});
write_json_file(reference, filePath);
fprintf('Saved benchmark reference: %s\n', filePath);
end

function filePath = normalize_json_path(filePath)
if isempty(filePath)
    filePath = '';
    return
end
if isstring(filePath)
    if ~isscalar(filePath)
        error('BLOPEX:benchmark_lobpcg_3d:InvalidJsonPath', ...
            'JSON paths must be scalar strings or character vectors.');
    end
    filePath = char(filePath);
elseif ~ischar(filePath)
    error('BLOPEX:benchmark_lobpcg_3d:InvalidJsonPath', ...
        'JSON paths must be character vectors or scalar strings.');
end
end

function filePath = make_diff_path(referencePath)
[folder, name, extension] = fileparts(referencePath);
if isempty(extension)
    extension = '.json';
end
filePath = fullfile(folder, [name, '_diff', extension]);
end

function write_json_file(value, filePath)
filePath = normalize_json_path(filePath);
if isempty(filePath)
    error('BLOPEX:benchmark_lobpcg_3d:InvalidJsonPath', ...
        'A JSON output path is required.');
end
try
    jsonText = jsonencode(value, 'PrettyPrint', true);
catch
    % Octave releases may support jsonencode but not the PrettyPrint option.
    jsonText = jsonencode(value);
end
[fileId, message] = fopen(filePath, 'w');
assert(fileId ~= -1, 'Could not open JSON output file %s: %s', filePath, message);
fileCleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, '%s\n', jsonText);
end

function diffReport = update_reference_and_diff(currentBenchmark, ...
        referencePath, diffPath)
if exist(referencePath, 'file') == 2
    reference = jsondecode(fileread(referencePath));
else
    write_benchmark_reference(currentBenchmark, referencePath);
    reference = jsondecode(fileread(referencePath));
end

diffReport = compare_benchmarks(currentBenchmark, reference);
print_benchmark_diff(diffReport, referencePath);
if isempty(diffPath)
    diffPath = make_diff_path(referencePath);
end
write_json_file(diffReport, diffPath);
fprintf('Saved benchmark diff: %s\n', diffPath);
end

function summary = summarize_solver_result(result, iterationLimit)
summary = struct(...
    'iterationLimit', iterationLimit, ...
    'iterations', result.iterationCount, ...
    'failureFlag', result.failureFlag, ...
    'solverSeconds', result.solverSeconds, ...
    'maxEigenvalueError', result.maxEigenvalueError, ...
    'eigenvectorSubspaceError', result.eigenvectorSubspaceError, ...
    'relativeResidual', result.relativeResidual, ...
    'orthogonalityError', result.orthogonalityError);
end

function diffReport = compare_benchmarks(currentRuns, reference)
comparisonTemplate = struct(...
    'gridShape', [], ...
    'blockSize', [], ...
    'referenceFound', false, ...
    'unpreconditioned', [], ...
    'modifiedIncompleteCholesky', []);
comparisons = repmat(comparisonTemplate, 1, numel(currentRuns));
referenceMatched = false(1, numel(reference.runs));

for currentIndex = 1:numel(currentRuns)
    currentRun = summarize_benchmark_case(currentRuns(currentIndex));
    matchingIndex = [];
    % Grid and requested block size identify a comparable benchmark case.
    for referenceIndex = 1:numel(reference.runs)
        referenceRun = reference.runs(referenceIndex);
        referenceGrid = reshape(double(referenceRun.gridShape), 1, []);
        currentGrid = reshape(double(currentRun.gridShape), 1, []);
        if isequal(referenceGrid, currentGrid) && ...
                referenceRun.blockSize == currentRun.blockSize
            matchingIndex = referenceIndex;
            break
        end
    end

    comparisons(currentIndex).gridShape = currentRun.gridShape;
    comparisons(currentIndex).blockSize = currentRun.blockSize;
    comparisons(currentIndex).referenceFound = ~isempty(matchingIndex);
    if isempty(matchingIndex)
        comparisons(currentIndex).unpreconditioned = ...
            compare_solver_results(currentRun.unpreconditioned, []);
        comparisons(currentIndex).modifiedIncompleteCholesky = ...
            compare_solver_results(currentRun.modifiedIncompleteCholesky, []);
    else
        referenceMatched(matchingIndex) = true;
        referenceRun = reference.runs(matchingIndex);
        comparisons(currentIndex).unpreconditioned = compare_solver_results( ...
            currentRun.unpreconditioned, referenceRun.unpreconditioned);
        comparisons(currentIndex).modifiedIncompleteCholesky = ...
            compare_solver_results(currentRun.modifiedIncompleteCholesky, ...
            referenceRun.modifiedIncompleteCholesky);
    end
end

unmatchedReferenceIndices = find(~referenceMatched);
referenceOnly = repmat(struct('gridShape', [], 'blockSize', []), ...
    1, numel(unmatchedReferenceIndices));
for unmatchedIndex = 1:numel(unmatchedReferenceIndices)
    referenceIndex = unmatchedReferenceIndices(unmatchedIndex);
    referenceOnly(unmatchedIndex) = struct( ...
        'gridShape', reshape(double(reference.runs(referenceIndex).gridShape), 1, []), ...
        'blockSize', reference.runs(referenceIndex).blockSize);
end

if isfield(reference, 'generatedAt')
    referenceGeneratedAt = reference.generatedAt;
else
    referenceGeneratedAt = '';
end
diffReport = struct(...
    'schemaVersion', 1, ...
    'generatedAt', benchmark_timestamp(), ...
    'referenceGeneratedAt', referenceGeneratedAt, ...
    'matlabVersion', version, ...
    'comparisons', comparisons, ...
    'referenceOnly', referenceOnly);
end

function comparison = compare_solver_results(current, reference)
if isempty(reference)
    comparison = struct(...
        'status', 'missingReference', ...
        'current', current, ...
        'reference', [], ...
        'delta', []);
    return
end

delta = struct(...
    'iterations', current.iterations - reference.iterations, ...
    'solverSeconds', current.solverSeconds - reference.solverSeconds, ...
    'maxEigenvalueError', current.maxEigenvalueError - reference.maxEigenvalueError, ...
    'eigenvectorSubspaceError', ...
        current.eigenvectorSubspaceError - reference.eigenvectorSubspaceError, ...
    'relativeResidual', current.relativeResidual - reference.relativeResidual, ...
    'orthogonalityError', current.orthogonalityError - reference.orthogonalityError, ...
    'failureFlagChanged', current.failureFlag ~= reference.failureFlag);
comparison = struct(...
    'status', 'matched', ...
    'current', current, ...
    'reference', reference, ...
    'delta', delta);
end

function print_benchmark_diff(diffReport, referencePath)
fprintf('\nBenchmark differences against %s\n', referencePath);
for runIndex = 1:numel(diffReport.comparisons)
    current = diffReport.comparisons(runIndex);
    fprintf('Grid %s, block size %d\n', ...
        mat2str(current.gridShape), current.blockSize);
    print_solver_diff('Unpreconditioned', current.unpreconditioned);
    print_solver_diff('Modified incomplete-Cholesky', ...
        current.modifiedIncompleteCholesky);
end
for runIndex = 1:numel(diffReport.referenceOnly)
    referenceOnly = diffReport.referenceOnly(runIndex);
    fprintf('Reference-only case: grid %s, block size %d\n', ...
        mat2str(referenceOnly.gridShape), referenceOnly.blockSize);
end
end

function print_solver_diff(label, comparison)
if strcmp(comparison.status, 'missingReference')
    fprintf('  %s: no matching reference case\n', label);
    return
end
delta = comparison.delta;
fprintf(['  %s: delta iterations %+d, time %+.3f s, eigenvalue error %+.3e, ', ...
    'subspace error %+.3e, residual %+.3e, orthogonality %+.3e, ', ...
    'failure flag changed %d\n'], label, delta.iterations, ...
    delta.solverSeconds, delta.maxEigenvalueError, ...
    delta.eigenvectorSubspaceError, delta.relativeResidual, ...
    delta.orthogonalityError, delta.failureFlagChanged);
end

function timestamp = benchmark_timestamp()
if exist('OCTAVE_VERSION', 'builtin')
    timestamp = datestr(now, 30);
else
    timestamp = char(datetime("now", 'Format', "yyyyMMdd'T'HHmmss"));
end
end

function remove_added_paths(folders)
for folderIndex = 1:numel(folders)
    currentPathEntries = strsplit(path, pathsep);
    if any(strcmp(currentPathEntries, folders{folderIndex}))
        rmpath(folders{folderIndex});
    end
end
end
